// ── MediAssist PDF Export Service ──
// Generates professional prescription & health report PDFs using jsPDF

import jsPDF from 'jspdf';

const MINT   = [0, 212, 168];
const DARK   = [8, 14, 28];
const BLUE   = [74, 159, 213];
const GRAY   = [136, 153, 187];
const LGRAY  = [240, 244, 255];
const WHITE  = [255, 255, 255];
const CORAL  = [255, 107, 107];
const AMBER  = [255, 170, 68];

function hex(rgb) { return `#${rgb.map(v => v.toString(16).padStart(2,'0')).join('')}`; }

// ── Header banner ──
function drawHeader(doc, title, subtitle) {
  // Dark banner
  doc.setFillColor(...DARK);
  doc.rect(0, 0, 210, 36, 'F');

  // Mint accent bar
  doc.setFillColor(...MINT);
  doc.rect(0, 0, 4, 36, 'F');

  // Logo circle
  doc.setFillColor(...MINT);
  doc.circle(22, 18, 9, 'F');
  doc.setTextColor(...WHITE);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('+', 22, 22, { align: 'center' });

  // App name
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...WHITE);
  doc.text('MediAssist Pro', 36, 16);
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...GRAY);
  doc.text('AI-Powered Health Companion', 36, 23);

  // Title right side
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...MINT);
  doc.text(title, 210 - 14, 16, { align: 'right' });
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...GRAY);
  doc.text(subtitle, 210 - 14, 23, { align: 'right' });

  return 44; // y after header
}

// ── Section heading ──
function sectionHead(doc, y, text, color = MINT) {
  doc.setFillColor(...color.map(v => Math.round(v * 0.15)));
  doc.roundedRect(14, y, 182, 8, 2, 2, 'F');
  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...color);
  doc.text(text.toUpperCase(), 18, y + 5.5);
  return y + 13;
}

// ── Info row ──
function infoRow(doc, y, label, value, labelColor = GRAY, valueColor = DARK, bold = false) {
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...labelColor);
  doc.text(label, 18, y);
  doc.setFont('helvetica', bold ? 'bold' : 'normal');
  doc.setTextColor(...valueColor);
  doc.text(String(value || '—'), 75, y);
  return y + 6;
}

// ── Two-column row ──
function twoCol(doc, y, l1, v1, l2, v2) {
  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...GRAY);
  doc.text(l1, 18, y);
  doc.setTextColor(...DARK);
  doc.text(String(v1 || '—'), 65, y);
  doc.setTextColor(...GRAY);
  doc.text(l2, 114, y);
  doc.setTextColor(...DARK);
  doc.text(String(v2 || '—'), 161, y);
  return y + 6;
}

// ── Divider ──
function divider(doc, y, color = [220, 228, 248]) {
  doc.setDrawColor(...color);
  doc.setLineWidth(0.3);
  doc.line(14, y, 196, y);
  return y + 4;
}

// ── Footer ──
function drawFooter(doc, pageNum) {
  const h = doc.internal.pageSize.height;
  doc.setFillColor(...LGRAY);
  doc.rect(0, h - 16, 210, 16, 'F');
  doc.setFontSize(7);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...GRAY);
  doc.text('⚕ Generated by MediAssist Pro · For medical reference only · Always consult a licensed physician', 14, h - 8);
  doc.text(`Page ${pageNum}`, 196, h - 8, { align: 'right' });
  doc.text(`Generated: ${new Date().toLocaleString('en-IN')}`, 105, h - 8, { align: 'center' });
}

