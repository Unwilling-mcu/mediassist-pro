// EXPORT 1 — Single Prescription PDF
// ══════════════════════════════════════════════
export function exportPrescriptionPDF(prescription, patient, user) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  let y = drawHeader(doc, 'PRESCRIPTION', `Rx #${prescription._id?.slice(-6)?.toUpperCase() || 'XXXXXX'}`);

  // ── Patient info ──
  y = sectionHead(doc, y, '👤 Patient Information');
  y = twoCol(doc, y, 'Patient Name', user?.name || patient?.name || '—', 'Patient ID', patient?.patientId || '—');
  y = twoCol(doc, y, 'Age / Gender', `${patient?.age || '?'} yrs / ${patient?.gender || '—'}`, 'Blood Group', patient?.bloodGroup || '—');
  y = twoCol(doc, y, 'Phone', patient?.phone || '—', 'City', patient?.city || 'Asansol, WB');
  if (patient?.allergies?.length) {
    y = infoRow(doc, y, '⚠ Allergies', patient.allergies.join(', '), [...CORAL], CORAL, true);
  }
  y = divider(doc, y + 2);

  // ── Rx details ──
  y = sectionHead(doc, y, '💊 Prescription Details', BLUE);

  // Big medicine name box
  doc.setFillColor(...LGRAY);
  doc.roundedRect(14, y, 182, 22, 3, 3, 'F');
  doc.setFillColor(...MINT);
  doc.roundedRect(14, y, 4, 22, 2, 2, 'F');

  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...DARK);
  doc.text(prescription.medicineName || '—', 22, y + 9);

  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...GRAY);
  doc.text(prescription.purpose || 'As prescribed', 22, y + 16);

  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...MINT);
  doc.text(prescription.dosage || '—', 190, y + 9, { align: 'right' });

  y += 27;

  y = twoCol(doc, y, 'Frequency',   prescription.frequency || '—', 'Timing',      prescription.timing || '—');
  y = twoCol(doc, y, 'Duration',    prescription.duration || '—',  'Days Supply', `${prescription.daysSupply || '—'} days`);
  y = twoCol(doc, y, 'Cost/Unit',   prescription.costPerUnit || '—', 'Refills Left', String(prescription.refillsLeft ?? '—'));
  y = twoCol(doc, y, 'Pharmacy',    prescription.pharmacy || '—', 'Status', (prescription.status || 'active').replace('_',' ').toUpperCase());
  y = divider(doc, y + 2);

  // ── Doctor info ──
  y = sectionHead(doc, y, '👨‍⚕️ Prescribing Physician', MINT);
  y = twoCol(doc, y, 'Doctor',      prescription.prescribedBy || '—', 'Date', prescription.prescribedAt || new Date().toLocaleDateString('en-IN'));
  y = divider(doc, y + 2);

  // ── Instructions ──
  if (prescription.notes) {
    y = sectionHead(doc, y, '📋 Instructions & Notes', AMBER);
    doc.setFillColor(255, 248, 230);
    doc.roundedRect(14, y, 182, 14, 2, 2, 'F');
    doc.setFontSize(8);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(...DARK);
    const lines = doc.splitTextToSize(prescription.notes, 170);
    doc.text(lines, 18, y + 5);
    y += 19;
  }

  // ── Dosage schedule visual ──
  y = sectionHead(doc, y, '⏰ Daily Schedule', MINT);
  const schedule = buildSchedule(prescription);
  const colW = 182 / schedule.length;
  schedule.forEach((slot, i) => {
    const x = 14 + i * colW;
    const active = slot.active;
    doc.setFillColor(...(active ? MINT.map(v => Math.round(v * 0.15)) : [245, 247, 255]));
    doc.roundedRect(x + 1, y, colW - 2, 18, 2, 2, 'F');
    if (active) {
      doc.setFillColor(...MINT);
      doc.circle(x + colW / 2, y + 7, 3, 'F');
    }
    doc.setFontSize(7);
    doc.setFont('helvetica', active ? 'bold' : 'normal');
    doc.setTextColor(...(active ? MINT : GRAY));
    doc.text(slot.time, x + colW / 2, y + 14, { align: 'center' });
  });
  y += 23;

  // ── Warning box ──
  doc.setFillColor(255, 242, 242);
  doc.roundedRect(14, y, 182, 12, 2, 2, 'F');
  doc.setFontSize(7);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...CORAL);
  doc.text('⚠  IMPORTANT:', 18, y + 5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(100, 40, 40);
  doc.text('This prescription is for the named patient only. Do not share medication. Keep out of reach of children.', 50, y + 5);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...GRAY);
  doc.text('Always take as directed by your physician. Report any adverse reactions immediately.', 18, y + 10);

  drawFooter(doc, 1);
  doc.save(`Prescription_${(prescription.medicineName || 'medicine').replace(/\s+/g,'-')}_${Date.now()}.pdf`);
}

