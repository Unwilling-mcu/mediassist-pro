// EXPORT 2 — Full Health Report PDF
// ══════════════════════════════════════════════
export function exportHealthReportPDF(patient, user, prescriptions = [], vitals = {}) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  let y = drawHeader(doc, 'HEALTH REPORT', new Date().toLocaleDateString('en-IN', { day:'numeric', month:'long', year:'numeric' }));

  // ── Patient summary card ──
  doc.setFillColor(...LGRAY);
  doc.roundedRect(14, y, 182, 34, 3, 3, 'F');

  // Avatar circle
  doc.setFillColor(...MINT);
  doc.circle(28, y + 17, 10, 'F');
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...WHITE);
  doc.text((user?.name || 'P').slice(0,1).toUpperCase(), 28, y + 21, { align: 'center' });

  doc.setFontSize(13);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...DARK);
  doc.text(user?.name || 'Patient', 42, y + 14);

  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...GRAY);
  doc.text(`ID: ${patient?.patientId || '—'} · ${patient?.gender || '—'} · ${patient?.age || '?'} yrs`, 42, y + 21);
  doc.text(`${patient?.city || 'Asansol'}, West Bengal · ${user?.email || ''}`, 42, y + 27);

  // BMI badge
  const bmi = patient?.bmi;
  const bmiColor = !bmi ? GRAY : bmi < 18.5 ? BLUE : bmi < 25 ? MINT : bmi < 30 ? AMBER : CORAL;
  doc.setFillColor(...bmiColor);
  doc.roundedRect(160, y + 8, 30, 18, 3, 3, 'F');
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...WHITE);
  doc.text(String(bmi || '—'), 175, y + 19, { align: 'center' });
  doc.setFontSize(7);
  doc.setFont('helvetica', 'normal');
  doc.text('BMI', 175, y + 24, { align: 'center' });

  y += 39;

  // ── Vitals summary ──
  y = sectionHead(doc, y, '💓 Current Vitals', CORAL);
  const vitalItems = [
    ['Heart Rate', `${vitals.heartRate || '74'} bpm`, CORAL],
    ['Blood Pressure', `${vitals.bp || '118/76'} mmHg`, BLUE],
    ['SpO2', `${vitals.spo2 || '99'}%`, MINT],
    ['Temperature', `${vitals.temp || '98.4'}°F`, AMBER],
  ];
  const vw = 182 / vitalItems.length;
  vitalItems.forEach(([lbl, val, col], i) => {
    const x = 14 + i * vw;
    doc.setFillColor(...col.map(v => Math.round(v * 0.12)));
    doc.roundedRect(x + 1, y, vw - 2, 20, 2, 2, 'F');
    doc.setFontSize(11);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(...col);
    doc.text(val, x + vw/2, y + 10, { align: 'center' });
    doc.setFontSize(7);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(...GRAY);
    doc.text(lbl, x + vw/2, y + 16, { align: 'center' });
  });
  y += 25;

  // Physical stats
  y = twoCol(doc, y, 'Height', `${patient?.heightCm || '—'} cm`, 'Weight', `${patient?.weightKg || '—'} kg`);
  y = twoCol(doc, y, 'Waist', `${patient?.waistCm || '—'} cm`, 'Blood Group', patient?.bloodGroup || '—');
  y = divider(doc, y + 2);

  // ── Medical history ──
  y = sectionHead(doc, y, '🏥 Medical History', BLUE);
  y = infoRow(doc, y, 'Chronic Conditions', (patient?.chronicConditions || []).join(', ') || 'None reported');
  y = infoRow(doc, y, '⚠ Drug Allergies', (patient?.allergies || []).join(', ') || 'None', GRAY, CORAL, true);
  y = infoRow(doc, y, 'Past Surgeries', (patient?.pastSurgeries || []).join(', ') || 'None');
  y = infoRow(doc, y, 'Family History', (patient?.familyHistory || []).join(', ') || 'None reported');
  y = twoCol(doc, y, 'Smoking', patient?.smokingStatus || 'Non-Smoker', 'Alcohol', patient?.alcoholUse || 'None');
  y = divider(doc, y + 2);

  // ── Active medications ──
  y = sectionHead(doc, y, '💊 Active Medications', MINT);
  if (!prescriptions.length) {
    doc.setFontSize(8); doc.setTextColor(...GRAY);
    doc.text('No active prescriptions recorded.', 18, y); y += 8;
  } else {
    // Table header
    doc.setFillColor(...DARK);
    doc.rect(14, y, 182, 7, 'F');
    doc.setFontSize(7); doc.setFont('helvetica', 'bold'); doc.setTextColor(...MINT);
    ['Medicine', 'Dosage', 'Frequency', 'Prescribed By', 'Status'].forEach((h, i) => {
      doc.text(h, [18, 65, 100, 135, 175][i], y + 5);
    });
    y += 9;

    prescriptions.forEach((rx, idx) => {
      if (idx % 2 === 0) { doc.setFillColor(...LGRAY); doc.rect(14, y - 1, 182, 7, 'F'); }
      doc.setFontSize(7); doc.setFont('helvetica', 'normal'); doc.setTextColor(...DARK);
      doc.text((rx.medicineName || '').slice(0, 22), 18, y + 4);
      doc.text((rx.dosage || '').slice(0, 14), 65, y + 4);
      doc.text((rx.frequency || '').slice(0, 16), 100, y + 4);
      doc.text((rx.prescribedBy || '').slice(0, 18), 135, y + 4);
      const sc = rx.status || 'active';
      doc.setTextColor(...(sc === 'active' ? MINT : sc === 'refill_needed' ? AMBER : CORAL));
      doc.text(sc.replace('_',' '), 175, y + 4);
      y += 7;
    });
    y += 4;
  }

  drawFooter(doc, 1);
  doc.save(`HealthReport_${(user?.name || 'Patient').replace(/\s+/g,'-')}_${Date.now()}.pdf`);
}

// ── helpers ──
function buildSchedule(rx) {
  const slots = [
    { time: 'Morning\n6-8 AM',    active: false },
    { time: 'Breakfast\n8-9 AM',  active: false },
    { time: 'Afternoon\n1-2 PM',  active: false },
    { time: 'Evening\n5-6 PM',    active: false },
    { time: 'Dinner\n8-9 PM',     active: false },
    { time: 'Bedtime\n10 PM',     active: false },
  ];
  const freq = (rx.frequency || '').toLowerCase();
  const timing = (rx.timing || '').toLowerCase();
  if (freq.includes('once'))    { slots[timing.includes('dinner') || timing.includes('night') ? 4 : 0].active = true; }
  if (freq.includes('twice'))   { slots[1].active = true; slots[4].active = true; }
  if (freq.includes('thrice') || freq.includes('three')) { slots[1].active = true; slots[3].active = true; slots[4].active = true; }
  if (timing.includes('morning')) slots[0].active = true;
  if (timing.includes('breakfast')) slots[1].active = true;
  if (timing.includes('dinner'))  slots[4].active = true;
  if (timing.includes('bed'))     slots[5].active = true;
  return slots;
}